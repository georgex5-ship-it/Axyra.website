// npm run check-content
// 1) Lists every [[EDIT ...]] placeholder still in the content files → PLACEHOLDERS.md
// 2) Checks every content file can be read (catches typos in YAML)
// 3) If the site has been built (dist/), warns if any placeholder leaked onto a published page
import fs from 'node:fs';
import path from 'node:path';
import { load } from 'js-yaml';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]);
const files = walk(path.join(root, 'content')).filter((f) => /\.ya?ml$/.test(f));

let problems = 0;
const rows = [];
for (const f of files) {
  const rel = path.relative(root, f);
  const text = fs.readFileSync(f, 'utf8');
  try { load(text); } catch (e) { problems++; console.error(`✖ ${rel}: ${e.message.split('\n')[0]}`); }
  text.split('\n').forEach((line, i) => {
    const m = line.match(/\[\[EDIT:?\s*([^\]]*)\]\]/);
    if (m && !line.trim().startsWith('#')) rows.push({ rel, line: i + 1, key: line.split(':')[0].trim().replace(/^- /, ''), what: m[1].trim() });
  });
}

const byFile = rows.reduce((a, r) => ((a[r.rel] ??= []).push(r), a), {});
let md = `# Placeholders still to fill\n\nGenerated by \`npm run check-content\` on ${new Date().toISOString().slice(0, 10)}.\n` +
  `Placeholders are hidden on the live site automatically, so you can publish before filling them all.\n\n` +
  `**Total: ${rows.length}**\n`;
for (const [file, list] of Object.entries(byFile)) {
  md += `\n## ${file}\n\n| Line | Field | What to write |\n|---|---|---|\n`;
  for (const r of list) md += `| ${r.line} | \`${r.key}\` | ${r.what.replace(/\|/g, '\\|')} |\n`;
}
fs.writeFileSync(path.join(root, 'PLACEHOLDERS.md'), md);
console.log(`• ${rows.length} placeholder(s) listed in PLACEHOLDERS.md`);

const dist = path.join(root, 'dist');
if (fs.existsSync(dist)) {
  const leaks = walk(dist).filter((f) => f.endsWith('.html') && fs.readFileSync(f, 'utf8').includes('[[EDIT'));
  if (leaks.length) { problems++; console.error(`✖ Placeholder text visible on: ${leaks.map((f) => path.relative(dist, f)).join(', ')}`); }
  else console.log('• No placeholder text on any published page (dist/)');
}
if (problems) { console.error(`\n${problems} problem(s) found.`); process.exit(1); }
console.log('✓ Content OK');
